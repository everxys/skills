#!/bin/sh
# Print client material from the state file.
# OUTPUT CONTAINS SECRETS. Show it only to the owner; never paste it into shared logs or tickets.
# Usage: sh gen-client.sh [--profile|--yaml-only|--links-only|--proxies-only] [--blocklist-url URL|--no-blocklist]
#   (default)       proxies + proxy-groups snippet and share links
#   --profile       a complete standalone Clash Verge Rev profile (save as dev\clash\vps-<ip>.yaml on host
#                   everx and check it with verge-mihomo -t). Defaults: ipv6: false + dns.ipv6: false
#                   (true only when an IPv6 entry exists), sniffer on (force-dns-mapping, parse-pure-ip,
#                   override-destination; HTTP/TLS/QUIC), fake-ip DNS, single IPv4 node unless install.sh
#                   --ipv6, and the user's rule set: RULE-SET blocklist, GEOSITE private, GEOSITE cn,
#                   GEOIP,CN,DIRECT,no-resolve, google domains, MATCH. GEOSITE cn already covers domestic
#                   sites: do not add more GEOSITE/GEOIP CN rules (tried and reverted 2026-11-10).
#   --proxies-only  proxies: list + share links, no proxy-groups (use when merging into a profile
#                   that already has its own groups, e.g. an existing "节点选择")
#   --blocklist-url rule-provider URL for my_blocklist (default http://127.0.0.1:28768/blocklist.yaml,
#                   the local helper on host everx; if nothing listens there mihomo keeps the cached file)
#   --no-blocklist  omit the rule-provider and its RULE-SET rule
STATE=${VR_STATE:-/usr/local/etc/xray/vless-reality.env}  # VR_STATE: point at a fake state file for tests
[ -r "$STATE" ] || { echo "no $STATE; run install.sh first" >&2; exit 1; }
# shellcheck disable=SC1090
. "$STATE"
mode=all; BL_URL=http://127.0.0.1:28768/blocklist.yaml; BL=1
while [ $# -gt 0 ]; do
  case "$1" in
    --profile|--yaml-only|--links-only|--proxies-only) mode=$1 ;;
    --blocklist-url) BL_URL=$2; shift ;;
    --no-blocklist) BL=0 ;;
    *) echo "unknown option: $1" >&2; exit 2 ;;
  esac; shift
done

entry() { # entry NAME SERVER PORT
  cat <<YAML
  - name: $1
    type: vless
    server: "$2"
    port: $3
    uuid: $UUID
    network: tcp
    udp: true
    tls: true
    flow: xtls-rprx-vision
    servername: $SNI
    client-fingerprint: chrome
    reality-opts:
      public-key: $PUBK
      short-id: $SID
YAML
}
link() { # link HOST PORT LABEL
  h=$1; case "$h" in *:*) h="[$h]" ;; esac
  printf 'vless://%s@%s:%s?encryption=none&flow=xtls-rprx-vision&security=reality&sni=%s&fp=chrome&pbk=%s&sid=%s&type=tcp#%s\n' \
    "$UUID" "$h" "$2" "$SNI" "$PUBK" "$SID" "$3"
}

names=""
groups() { # groups NAME1 [NAME2]: select group (+ fallback when two stacks were requested)
  if [ $# -eq 2 ]; then
    cat <<YAML
  - name: $NAME-auto
    type: fallback
    proxies: [$1, $2]
    url: https://www.gstatic.com/generate_204
    interval: 300
    timeout: 3000
    lazy: true
  - name: 节点选择
    type: select
    proxies: [$NAME-auto, $1, $2]
YAML
  else
    printf '  - name: 节点选择\n    type: select\n    proxies: [%s]\n' "$1"
  fi
}

if [ "$mode" = --profile ]; then
  V6=false; [ "$PUB6" != none ] && V6=true
  [ "$PUB4" != none ] && DIAL=$PUB4 || DIAL=$PUB6
  cat <<YAML
# Clash Verge Rev profile for $DIAL ($NAME), generated by deploy-vless-reality gen-client.sh --profile.
# Reality SNI/dest: $SNI. Contains secrets: keep it out of shared folders and version control.
# Verge overrides mixed-port/allow-lan/tun/ports, so they are omitted. ipv6 below must match Verge's own
# IPv6 switch and the global Merge.yaml (both override this file; see references/verge.md).
mode: rule
log-level: info
ipv6: $V6
unified-delay: true
tcp-concurrent: true
keep-alive-interval: 15
keep-alive-idle: 600
find-process-mode: off

sniffer:
  enable: true
  force-dns-mapping: true
  parse-pure-ip: true
  override-destination: true
  sniff:
    HTTP:
      ports: [80, 8080-8880]
    TLS:
      ports: [443, 8443]
    QUIC:
      ports: [443, 8443]

dns:
  enable: true
  ipv6: $V6
  use-hosts: true
  use-system-hosts: true
  enhanced-mode: fake-ip
  fake-ip-range: 198.18.0.1/16
  fake-ip-filter:
    - "*.lan"
    - "*.local"
    - "+.msftconnecttest.com"
    - "+.msftncsi.com"
    - "time.*.com"
    - "ntp.*.com"
  default-nameserver:
    - 223.5.5.5
    - 119.29.29.29
  nameserver:
    - https://doh.pub/dns-query
    - https://dns.alidns.com/dns-query
  proxy-server-nameserver:
    - https://doh.pub/dns-query
    - https://dns.alidns.com/dns-query

proxies:
YAML
  [ "$PUB6" != none ] && { entry "$NAME-v6" "$PUB6" "$PUBPORT6"; names="$names $NAME-v6"; }
  [ "$PUB4" != none ] && { entry "$NAME-v4" "$PUB4" "$PUBPORT"; names="$names $NAME-v4"; }
  printf '\nproxy-groups:\n'
  # shellcheck disable=SC2086
  groups $names
  if [ "$BL" = 1 ]; then
    cat <<YAML

rule-providers:
  my_blocklist:
    type: http
    behavior: domain
    url: "$BL_URL"
    path: ./rules/my_blocklist.yaml
    interval: 3600
    proxy: DIRECT
YAML
  fi
  printf '\nrules:\n'
  [ "$BL" = 1 ] && echo "  - RULE-SET,my_blocklist,REJECT"
  cat <<YAML
  - GEOSITE,private,DIRECT
  - GEOSITE,cn,DIRECT
  - GEOIP,CN,DIRECT,no-resolve
  - DOMAIN-KEYWORD,google,节点选择
  - DOMAIN-KEYWORD,gmail,节点选择
  - DOMAIN-SUFFIX,google.com,节点选择
  - MATCH,节点选择
YAML
  exit 0
fi
if [ "$mode" != --links-only ]; then
  if [ "$mode" = --proxies-only ]; then echo "# --- paste into the profile's proxies: and add the names to its own groups (no top-level ipv6/mixed-port/allow-lan/tun) ---"
  else echo "# --- paste into the profile's proxies: / proxy-groups: (do not add top-level ipv6/mixed-port/allow-lan/tun) ---"; fi
  echo "proxies:"
  [ "$PUB6" != none ] && { entry "$NAME-v6" "$PUB6" "$PUBPORT6"; names="$names $NAME-v6"; }
  [ "$PUB4" != none ] && { entry "$NAME-v4" "$PUB4" "$PUBPORT"; names="$names $NAME-v4"; }
  echo
fi
if [ "$mode" = all ] || [ "$mode" = --yaml-only ]; then
  echo "# WARNING: the group below is named 节点选择; if the target profile already has a group with that"
  echo "# name, do not paste a second one: add the proxy names to the existing group, or use --proxies-only."
  echo "proxy-groups:"
  # shellcheck disable=SC2086
  groups $names
  echo
fi
if [ "$mode" != --yaml-only ]; then
  echo "# --- share links ---"
  [ "$PUB6" != none ] && link "$PUB6" "$PUBPORT6" "$NAME-v6"
  [ "$PUB4" != none ] && link "$PUB4" "$PUBPORT" "$NAME-v4"
fi
exit 0
